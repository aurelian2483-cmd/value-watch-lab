'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const M=require('../paper-lab/method-selection.js');
const ids=M.methods.map(x=>x.id);
assert.deepEqual(ids,['current','experimental','hybrid','compare','reliability','bottleneck','racing-top-four']);
assert.equal(new Set(ids).size,7);
assert.equal(M.methods.find(m=>m.id==='compare').kind,'tool');
assert.equal(M.methods.find(m=>m.id==='bottleneck').kind,'research-readiness');
assert.deepEqual(M.normalize(['current','hybrid','current','bad','compare','bottleneck']),['current','hybrid','compare','bottleneck']);
assert.deepEqual(M.normalize([],[]),[]);
assert.deepEqual(M.normalize('broken'),['current']);
assert.deepEqual(M.toggle(['current'],'experimental'),['current','experimental']);
assert.deepEqual(M.toggle(['current','experimental'],'current'),['experimental']);
assert.deepEqual(M.toggle(['current'],'current'),[]);
assert.deepEqual(M.toggle([], 'racing-top-four'),['racing-top-four']);
assert.deepEqual(M.toggle(['compare'],'nonexistent'),['compare']);
assert.deepEqual(M.fromStorage('["hybrid","compare","hybrid"]','current'),['hybrid','compare']);
assert.deepEqual(M.fromStorage('[]','current'),[]);
assert.deepEqual(M.fromStorage('malformed','hybrid'),['hybrid']);
assert.deepEqual(M.fromStorage('malformed','invalid'),['current']);
assert.deepEqual(M.fromStorage('{"not":"an array"}','compare'),['compare']);
assert.deepEqual(M.fromStorage('[null,123,"current",{}, "bottleneck"]','current'),['current','bottleneck']);
const css=fs.readFileSync('paper-lab/method-tiles.css','utf8');
assert(css.includes('.engine-method-tile[aria-pressed="true"]'));
assert(css.includes('grid-template-columns:repeat(2,minmax(0,1fr))'));
assert(css.includes('.engine-select-legacy'));
for(const page of ['index.html','paper-lab/index.html']){
  const html=fs.readFileSync(page,'utf8');
  assert(html.includes('id="engine-methods"'));
  assert(html.includes('Select one or more methods'));
  for(const id of ids)assert(html.includes('data-method="'+id+'"'),id+' missing from '+page);
  assert(html.includes('method-selection.js?v=1'));
  assert(html.includes('method-tiles.css?v=multiselect-2'));
  assert(html.includes('id="engine-select"'),'backward compatible preference select');
  assert(html.indexOf('method-selection.js') < html.indexOf('desk-compact-20261116.js'));
  assert(!html.includes('data-engine="'));
}
const desk=fs.readFileSync('paper-lab/desk-compact-20261116.js','utf8');
assert(desk.includes('function renderEngineMode('));
assert(desk.includes('renderEngineMode(evaluation,view,content'));
assert(desk.includes('M.toggle(selectedMethods,tile.dataset.method)'));
assert(desk.includes('selectedMethods.length === 1'));
assert(desk.includes('M.preferenceKey'));
assert(desk.includes("storedDecimal.toFixed(2) + ' (unverified, not live)'"),'Saved prices must be visibly labelled historical');
assert(desk.includes("' · no recorded odds'"),'Missing quotes must be shown as unavailable');
assert(desk.includes("new URL('market-intelligence/', rootURL)"),'Existing market archive must remain discoverable');
console.log('PASS: 7 method tiles, multiselect transitions, persistence, both entrypoints and safe mode rendering contracts');
