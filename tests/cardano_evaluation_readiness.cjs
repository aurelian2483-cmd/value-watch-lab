'use strict';
const assert=require('node:assert/strict');
const R=require('../cardano-lab/evaluation-readiness.js');
const base=()=>({experiment_id:'exp-1',evidence:[{integrity_status:'CONSISTENT_UNVERIFIED',eligible_for_scoring:false}],accepted_integrity_count:1,rejected_count:0,externally_verified:false,eligible_for_real_world_scoring:false,research_only:true,model_validation:'UNVALIDATED',publication_gate:'BLOCKED'});
const good=R.assess(base(),'exp-1');
assert.equal(good.offline_integrity_complete,true);
assert.equal(good.eligible_for_real_world_scoring,false);
assert.deepEqual(good.reasons,['PUBLISHER_AUTHENTICATION_MISSING','OUTCOME_VERIFICATION_MISSING']);
const empty=base();empty.evidence=[];empty.accepted_integrity_count=0;
assert.ok(R.assess(empty,'exp-1').reasons.includes('NO_EVIDENCE'));
const bad=base();bad.evidence.push({integrity_status:'REJECTED',eligible_for_scoring:false});bad.rejected_count=1;
assert.equal(R.assess(bad,'exp-1').offline_integrity_complete,false);
const forged=base();forged.eligible_for_real_world_scoring=true;
assert.ok(R.assess(forged,'exp-1').reasons.includes('REGISTER_SAFETY_GATE_MISMATCH'));
const count=base();count.accepted_integrity_count=5;
assert.ok(R.assess(count,'exp-1').reasons.includes('REGISTER_COUNT_MISMATCH'));
const status=base();status.evidence[0].eligible_for_scoring=true;
assert.ok(R.assess(status,'exp-1').reasons.includes('INVALID_EVIDENCE_STATUS'));
assert.throws(()=>R.assess(base(),'other'),/Matching/);
console.log('PASS Cardano evaluation readiness and fail-closed safety cases');
