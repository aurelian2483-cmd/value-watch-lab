'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const F=require('../cardano-lab/fixture-evaluation.js');
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const rows=[{id:'fixture-1',fixture_only:true,issued_at_utc:'2026-11-01T10:00:00Z',event_at_utc:'2026-11-02T10:00:00Z',resolved_at_utc:'2026-11-02T12:00:00Z',probability:0.7,baseline_probability:0.5,outcome:1,dataset_split:'HOLDOUT'}];
const bytes=Buffer.from(JSON.stringify(rows));
const exp={schema_version:1,id:'fixture-test',hypothesis:'Synthetic evaluation only',sport:'tennis',lane:'experimental',status:'PROPOSED',created_at_utc:'2026-11-11T12:00:00Z',updated_at_utc:'2026-11-11T12:00:00Z',dataset_sha256:sha(bytes),method_version:'fixture-v1',seed:5,sources:[{url:'https://example.org/fixture',observed_at_utc:'2026-11-11T12:00:00Z'}],research_only:true,model_validation:'UNVALIDATED',publication_gate:'BLOCKED'};
const result=F.run(exp,bytes,'binary');
assert.equal(result.metrics.sample_size,1);
assert.equal(result.fixture_only,true);
assert.equal(result.publication_gate,'BLOCKED');
assert.equal(result.eligible_for_real_world_scoring,false);
assert.match(result.result_sha256,/^[a-f0-9]{64}$/);
assert.deepEqual(F.run(exp,bytes,'binary'),result);
assert.throws(()=>F.run(exp,Buffer.from(JSON.stringify([...rows,{...rows[0],id:'x'}])),'binary'),/Fixture hash/);
const unmarked=Buffer.from(JSON.stringify([{...rows[0],fixture_only:false}]));
assert.throws(()=>F.run({...exp,dataset_sha256:sha(unmarked)},unmarked,'binary'),/synthetic fixture/);
assert.throws(()=>F.run({...exp,publication_gate:'OPEN'},bytes,'binary'),/Invalid experiment/);
assert.throws(()=>F.run(exp,bytes,'other'),/Unknown fixture/);
const mrows=[{id:'three-way',fixture_only:true,issued_at_utc:'2026-11-01T10:00:00Z',event_at_utc:'2026-11-02T10:00:00Z',resolved_at_utc:'2026-11-02T12:00:00Z',dataset_split:'HOLDOUT',outcomes:['home','draw','away'],actual_outcome:'home',probabilities:[0.6,0.2,0.2],baseline_probabilities:[0.4,0.3,0.3]}];
const mb=Buffer.from(JSON.stringify(mrows));
const multi=F.run({...exp,dataset_sha256:sha(mb)},mb,'multiclass');
assert.equal(multi.metrics.outcome_count,3);
assert.equal(multi.publication_gate,'BLOCKED');
console.log('PASS deterministic fixture-only binary/multiclass evaluation with provenance and safety gates');
