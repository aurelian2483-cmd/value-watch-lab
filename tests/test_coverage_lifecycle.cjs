'use strict';
const assert=require('node:assert/strict');
const M=require('../research/coverage-lifecycle.js');
const now=Date.parse('2026-11-14T12:00:00Z');
const gate={research_only:true,model_validation:'UNVALIDATED',publication_gate:'BLOCKED'};
const future={...gate,startUTC:'2026-11-14T13:00:00Z'};
assert.equal(M.lifecycle(future,now),'SCHEDULED');
assert.equal(M.eligibleForFutureResearch(future,now),true);
assert.equal(M.lifecycle({...future,startUTC:'2026-11-14T11:00:00Z'},now),'START_TIME_PASSED_UNCONFIRMED');
assert.equal(M.eligibleForFutureResearch({...future,startUTC:'2026-11-14T11:00:00Z'},now),false);
assert.equal(M.lifecycle({...future,status:'started'},now),'STARTED');
assert.equal(M.lifecycle({...future,status:'finished'},now),'COMPLETED_UNVERIFIED');
assert.equal(M.lifecycle({...future,status:'finished',result_verified:true},now),'RESULT_VERIFIED');
for(const status of ['postponed','cancelled','abandoned'])assert.equal(M.eligibleForFutureResearch({...future,status},now),false);
assert.equal(M.eligibleForFutureResearch({...future,publication_gate:'OPEN'},now),false);
assert.equal(M.lifecycle({...future,startUTC:'invalid'},now),'UNKNOWN');
assert.equal(M.coverage({sport:'racing',observed:0,expected:null}).state,'COVERAGE_UNVERIFIED');
assert.equal(M.coverage({sport:'racing',observed:0,expected:0}).state,'COUNTS_MATCH_NOT_CERTIFIED');
assert.equal(M.coverage({sport:'racing',observed:2,expected:5}).missing,3);
assert.equal(M.coverage({sport:'racing',observed:0,expected:5,sourceStatus:'UNAVAILABLE'}).state,'SOURCE_UNVERIFIED');
const result=M.reconcile([future,{...future,startUTC:'2026-11-14T11:00:00Z'},{...future,status:'cancelled'}],now);
assert.equal(result.eligible.length,1);
assert.equal(result.counts.SCHEDULED,1);
assert.equal(result.counts.START_TIME_PASSED_UNCONFIRMED,1);
assert.equal(result.counts.CANCELLED,1);
console.log('PASS: research-only coverage, time ambiguity, lifecycle and gate tests');
