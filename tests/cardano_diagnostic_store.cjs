'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const W=require('../cardano-lab/research-workflow.js');
const E=require('../cardano-lab/experiment-store.js');
const D=require('../cardano-lab/diagnostic-store.js');
const hash=crypto.createHash('sha256').update('data').digest('hex');
const exp={schema_version:1,id:'exp-memory',hypothesis:'Test diagnostic memory',sport:'football',lane:'applied',status:'PROPOSED',created_at_utc:'2026-11-11T12:00:00Z',updated_at_utc:'2026-11-11T12:00:00Z',dataset_sha256:hash,method_version:'v1',seed:2,sources:[{url:'https://example.org/research',observed_at_utc:'2026-11-11T12:00:00Z'}],model_validation:'UNVALIDATED',publication_gate:'BLOCKED',research_only:true};
const map=new Map(),storage={getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,v)};
const ledger=E.store(storage);ledger.append(exp);
const memory=D.store(storage);
const diagnostic=W.inspect(exp,[],[]);
assert.equal(memory.append(diagnostic,ledger),1);
assert.equal(memory.load()[0].publication_gate,'BLOCKED');
assert.ok(memory.load()[0].issues.includes('NO_EVIDENCE'));
assert.throws(()=>memory.append(diagnostic,ledger),/Duplicate/);
const bad={...diagnostic,publication_gate:'OPEN'};
assert.throws(()=>memory.append(bad,ledger),/Unsafe/);
assert.throws(()=>memory.append({...diagnostic,experiment_id:'missing'},ledger),/Invalid evidence snapshot/);
assert.throws(()=>memory.append({...diagnostic,experiment_id:'missing',evidence:{...diagnostic.evidence,experiment_id:'missing'}},ledger),/matching experiment/);
const copy=memory.load();copy[0].issues.push('MUTATED');
assert.ok(!memory.load()[0].issues.includes('MUTATED'));
const saved=map.get(D.KEY);
map.set(D.KEY,'{broken');assert.throws(()=>memory.load(),/Corrupt/);
assert.throws(()=>memory.append({...diagnostic,experiment_id:'other'},ledger));
assert.equal(map.get(D.KEY),'{broken');
map.set(D.KEY,saved);
assert.equal(D.parse(memory.exportJSON()).length,1);
console.log('PASS diagnostic memory persistence, ledger match, duplicates, safety, corruption and isolation');
