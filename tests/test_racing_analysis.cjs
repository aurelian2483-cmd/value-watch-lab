const assert=require('node:assert/strict');
const C=require('../racing-research/analysis-core.js');
const p=C.priceAnalysis(6,20,15);
assert.ok(Math.abs(p.breakEven-1/6)<1e-12);
assert.ok(Math.abs(p.ev-.2)<1e-12);
assert.ok(Math.abs(p.lowerEV+.1)<1e-12);
assert.equal(C.priceAnalysis(4,'','').ev,null);
assert.equal(C.priceAnalysis(4,0,0).ev,-1);
for(const odds of ['',1,0,-3,Infinity,'bad'])assert.throws(()=>C.priceAnalysis(odds,20,10));
for(const [prob,lower]of [[101,''],[-1,''],[20,25],['',5],['bad',''],[20,'bad']])assert.throws(()=>C.priceAnalysis(4,prob,lower));
const m=C.marketBaseline([{id:'a',odds:2},{id:'b',odds:3},{id:'c',odds:4}]);
assert.ok(Math.abs(m.overround-1/12)<1e-12);
assert.ok(Math.abs(m.probabilities.reduce((s,p)=>s+p.probability,0)-1)<1e-12);
assert.ok(Math.abs(m.probabilities[0].probability-6/13)<1e-12);
assert.throws(()=>C.marketBaseline([{id:'a',odds:2},{id:'b',odds:''}]));
assert.throws(()=>C.marketBaseline([{id:'a',odds:2},{id:'a',odds:3}]));
const now=Date.parse('2026-11-03T18:00:00Z');
const r={startUTC:'2026-11-03T19:00:00Z',runner_observed_at_utc:'2026-11-03T17:45:00Z',race_stage:'DORMANT',runner_data_status:'SINGLE_SOURCE_RUNNERS_OBSERVED',active_runner_count:2,runners:[{horse_id:'a',active_runner:true,runner_status:'RUNNER'},{horse_id:'b',active_runner:true,runner_status:'RUNNER'}]};
assert.equal(C.fieldStatus(r,now).current,true);
assert.equal(C.fieldStatus({...r,runner_observed_at_utc:'2026-11-03T17:29:59Z'},now).current,false);
assert.equal(C.fieldStatus({...r,runner_observed_at_utc:'2026-11-03T18:01:00Z'},now).current,false);
assert.equal(C.fieldStatus({...r,startUTC:'2026-11-03T17:59:00Z'},now).current,false);
assert.equal(C.fieldStatus({...r,active_runner_count:3},now).current,false);
assert.equal(C.fieldStatus({...r,runners:[r.runners[0],r.runners[0]]},now).current,false);
assert.equal(C.fieldStatus({...r,race_stage:'WEIGHEDIN'},now).current,false);
assert.equal(C.safeURL('javascript:alert(1)'),null);
assert.equal(C.safeURL('https://user:password@example.com'),null);
assert.equal(C.safeURL('https://example.com/report'),'https://example.com/report');
console.log('Racing analysis checks passed: EV, uncertainty bounds, overround, field freshness, duplicate runners and source URLs.');
