'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const core = require('../market-intelligence/comparison-core.cjs');
const {mergePoll, render} = require('../scripts/render_pl_comparison.cjs');
const now = Date.parse('2026-11-26T12:00Z');
const start = now + 60 * 60000;
const iso = ms => new Date(ms).toISOString();
const fixture = {home:'Manchester United',away:'Tottenham Hotspur',kickoff_utc:iso(start)};
const books = new Set(['skybet','other_book']);
const base = {sport_key:'soccer_epl',market:'h2h',settlement:core.market,event_id:'abcdefghijklmnop',home:'Man Utd',away:'Spurs',
  start_utc:iso(start),observed_at_utc:iso(now-60000),checked_at_utc:iso(now),receipt_sha256:'a'.repeat(64),bookmaker:'skybet',
  prices:{home:2,draw:3,away:4}};
const poll = {status:'ok',checked:iso(now),records:[base,{...base,bookmaker:'other_book',prices:{home:2.1,draw:2.9,away:4}}]};
const empty = {observations:[]};
const accept = (rows,records) => core.matchPoll(rows,records,now,books);
assert.equal(accept([fixture],poll.records).accepted.length,2);
assert.equal(accept([fixture,{...fixture,home:'Man United'}],[base]).rejects.no_match,1);
assert.equal(accept([fixture],[base,{...base,event_id:'zzzzzzzzzzzzzzzz'}]).rejects.no_match,2);
assert.equal(accept([fixture],[{...base,prices:{home:2,draw:3}}]).rejects.no_market,1);
assert.equal(accept([fixture],[{...base,settlement:'INCLUDING_OVERTIME'}]).rejects.no_market,1);
assert.equal(accept([fixture],[{...base,observed_at_utc:iso(now-31*60000)}]).rejects.expired,1);
const math = core.metrics(base.prices);
assert(Math.abs(math.overround-1/12)<1e-10);
assert(Math.abs(math.outcomes.home.probability-6/13)<1e-10);
assert(Math.abs(math.outcomes.home.fairOdds-13/6)<1e-10);
assert.equal(core.metrics({home:2,away:4}),null);
const history = mergePoll(empty,poll,[fixture],books,now);
const late = start-10*60000;
const later = {...base,observed_at_utc:iso(late),checked_at_utc:iso(late),prices:{home:1.9,draw:3.2,away:4}};
const two = mergePoll(history,{status:'ok',checked:iso(late),records:[later]},[fixture],books,late);
assert.equal(two.observations.length,3);
assert.equal(mergePoll(two,{status:'ok',checked:iso(late+1000),records:[{...later,checked_at_utc:iso(late+1000)}]},[fixture],books,late+1000).observations.length,4);
const same = two.observations.filter(row=>row.bookmaker==='skybet');
assert.equal(core.movement(same,start,late).close,null);
assert(Math.abs(core.movement(same,start,start).outcomes.home.closingComparison-(2/1.9-1))<1e-10);
assert.equal(core.movement(two.observations,start,start),null);
assert.equal(core.comparison(history.observations,now+31*60000).books,0);
const html = fs.readFileSync('market-intelligence/index.html','utf8');
assert.equal(render(html,history,[fixture],books,false,now),html);
const shown = render(html,history,[fixture],books,true,now);
assert.match(shown,/Best found among 2 checked/);
assert.match(shown,/Home · 2.1 · other_book/);
assert.match(render(html,history,[fixture],new Set(['skybet']),true,now),/One bookmaker checked/);
assert.match(render(html,history,[fixture],books,true,now+31*60000),/Prices expired/);
const failed = mergePoll(history,{status:'failed',checked:iso(now+1),records:[]},[fixture],books,now+1);
assert.equal(failed.observations.length,2);
assert.match(render(html,failed,[fixture],books,true,now+1),/Source failed · current prices withheld/);
assert.doesNotMatch(render(html,failed,[fixture],books,true,now+1),/Best found/);
assert.equal(mergePoll(history,null,[fixture],books,now).status,'failed');
assert.equal(mergePoll(history,{status:'ok',checked:iso(now+1),records:[]},[fixture],books,now+1).status,'empty');
console.log('PASS: PL joins, full-market arithmetic, repeated polls, close, expiry, failed source and display switch');
