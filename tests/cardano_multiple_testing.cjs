'use strict';
const assert=require('node:assert/strict'),M=require('../cardano-lab/multiple-testing.js');
const h=(id,p,pre_registered=true)=>({id,p_value:p,pre_registered});
const data=[h('c',.04,false),h('a',.001),h('b',.02),h('d',.8)];
const result=M.audit(data);
assert.equal(result.hypothesis_count,4);
assert.deepEqual(result.results.map(r=>r.id),['c','a','b','d'],'preserves input order');
assert.equal(result.holm_rejections,1);
assert.equal(result.bh_rejections,2);
assert.equal(result.exploratory_count,1);
assert.equal(result.results[1].holm_adjusted_p,.004);
assert.equal(result.results[1].holm_reject,true);
assert.equal(result.results[0].holm_reject,false);
assert.equal(result.publication_gate,'BLOCKED');
assert.deepEqual(M.audit(data),result,'deterministic');
assert.throws(()=>M.audit([]),/Nonempty/);
assert.throws(()=>M.audit([h('a',.1),h('a',.2)]),/duplicate/);
assert.throws(()=>M.audit([h('a',NaN)]),/p_value/);
assert.throws(()=>M.audit([h('a',-1)]),/p_value/);
assert.throws(()=>M.audit([h('a',1.1)]),/p_value/);
assert.throws(()=>M.audit([{id:'a',p_value:.02}]),/pre_registered/);
for(const alpha of [0,1,-.1,NaN])assert.throws(()=>M.audit([h('a',.01)],{alpha}),/alpha/);
assert.equal(M.audit([h('a',.01)]).holm_rejections,1);
console.log('PASS Cardano multiple-testing correction and negative cases');
