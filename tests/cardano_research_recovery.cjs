'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const L=require('../cardano-lab/experiment-store.js');
const W=require('../cardano-lab/research-workflow.js');
const D=require('../cardano-lab/diagnostic-store.js');
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
const data=Buffer.from('controlled fixture');
const experiment={schema_version:1,id:'recovery-1',hypothesis:'Archive and restore a research diagnostic',sport:'tennis',lane:'experimental',status:'PROPOSED',created_at_utc:'2026-11-11T12:00:00Z',updated_at_utc:'2026-11-11T12:00:00Z',dataset_sha256:sha('dataset'),method_version:'fixture-v1',seed:7,sources:[{url:'https://example.org/research',observed_at_utc:'2026-11-11T12:00:00Z'}],model_validation:'UNVALIDATED',publication_gate:'BLOCKED',research_only:true};
function storage(){const m=new Map();return {getItem:k=>m.has(k)?m.get(k):null,setItem:(k,v)=>m.set(k,v),raw:m};}
const source=storage(),ledger=L.store(source),memory=D.store(source);
ledger.append(experiment);
const capture={bytes:data,receipt:{source_url:'https://example.org/research',source_sha256:sha(data),captured_at_utc:'2026-11-11T12:00:00Z',byte_length:data.length}};
const audit={computed_sha256:sha(data),consistent:true,errors:[],eligible_for_scoring:false,source_authenticated:false,outcome_verified:false};
const report=W.inspect(experiment,[capture],[audit]);
assert.equal(report.readiness.offline_integrity_complete,true);
assert.equal(report.eligible_for_real_world_scoring,false);
assert.equal(memory.append(report,ledger),1);
const ledgerBackup=ledger.exportJSON(),diagnosticBackup=memory.exportJSON();
const restored=storage(),restoredLedger=L.store(restored),restoredMemory=D.store(restored);
assert.equal(restoredLedger.importJSON(ledgerBackup),1);
const imported=D.parse(diagnosticBackup);
assert.equal(imported.length,1);
assert.equal(restoredMemory.append(imported[0],restoredLedger),1);
assert.deepEqual(restoredMemory.load(),memory.load());
assert.throws(()=>restoredMemory.append(imported[0],restoredLedger),/Duplicate/);
const before=restored.raw.get(D.KEY);
assert.throws(()=>restoredMemory.append({...imported[0],publication_gate:'OPEN'},restoredLedger),/Unsafe/);
assert.equal(restored.raw.get(D.KEY),before);
const invalid=JSON.parse(diagnosticBackup);invalid.records[0].evidence.experiment_id='forged';
assert.throws(()=>D.parse(JSON.stringify(invalid)),/Invalid evidence/);
assert.equal(restored.raw.get(D.KEY),before);
restored.raw.set(D.KEY,'corrupt');
assert.throws(()=>restoredMemory.load(),/Corrupt/);
assert.equal(restored.raw.get(D.KEY),'corrupt');
console.log('PASS end-to-end fixture, backup restore, isolation, corruption and blocked scoring');
