'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const W=require('../cardano-lab/research-workflow.js');
const sha=crypto.createHash('sha256').update('sample').digest('hex');
const exp={schema_version:1,id:'exp-flow-1',hypothesis:'Demonstrate fail-closed integration',sport:'football',lane:'applied',status:'PROPOSED',created_at_utc:'2026-11-11T12:00:00Z',updated_at_utc:'2026-11-11T12:00:00Z',dataset_sha256:sha,method_version:'demo-v1',seed:1,sources:[{url:'https://example.org/research',observed_at_utc:'2026-11-11T12:00:00Z'}],model_validation:'UNVALIDATED',publication_gate:'BLOCKED',research_only:true};
const bytes=Buffer.from('sample');
const capture={bytes,receipt:{source_url:'https://example.org/research',source_sha256:sha,captured_at_utc:'2026-11-11T12:00:00Z',byte_length:bytes.length}};
const audit={computed_sha256:sha,consistent:true,errors:[],eligible_for_scoring:false,source_authenticated:false,outcome_verified:false};
const ok=W.inspect(exp,[capture],[audit]);
assert.equal(ok.evidence.accepted_integrity_count,1);
assert.equal(ok.readiness.offline_integrity_complete,true);
assert.equal(ok.evaluation_performed,false);
assert.equal(ok.eligible_for_real_world_scoring,false);
assert.equal(ok.publication_gate,'BLOCKED');
assert.ok(ok.issues.includes('EXPERIMENT_NOT_COMPLETED'));
assert.ok(ok.issues.includes('OUTCOME_VERIFICATION_MISSING'));
const empty=W.inspect(exp,[],[]);
assert.ok(empty.issues.includes('NO_EVIDENCE'));
const rejected=W.inspect(exp,[capture],[{...audit,consistent:false,errors:['TEST_REJECTION']}]);
assert.equal(rejected.readiness.offline_integrity_complete,false);
assert.ok(rejected.issues.includes('REJECTED_EVIDENCE_PRESENT'));
assert.throws(()=>W.inspect({...exp,publication_gate:'OPEN'},[],[]),/Invalid experiment/);
assert.throws(()=>W.inspect(exp,[capture],[{...audit,computed_sha256:'0'.repeat(64)}]),/Audit hash/);
assert.throws(()=>W.inspect(exp,[capture],[]),/Every capture requires/);
console.log('PASS Cardano integrated diagnostic workflow, missing/rejected/tampered evidence and safety gates');
