'use strict';
const assert=require('node:assert/strict'),crypto=require('node:crypto');
const R=require('../cardano-lab/evidence-register.js'),A=require('../cardano-lab/capture-audit.js');
const bytes=Buffer.from('synthetic fixture'),now=Date.parse('2026-11-11T18:00:00Z');
const capture={bytes,receipt:{source_url:'https://example.org/results',source_sha256:crypto.createHash('sha256').update(bytes).digest('hex'),captured_at_utc:'2026-11-11T18:00:00Z',byte_length:bytes.length,http_status:200,verification_level:'HTTPS_RESPONSE_CAPTURED',publisher_authenticated:false,outcome_verified:false,research_only:true,model_validation:'UNVALIDATED',publication_gate:'BLOCKED'}};
const audit=A.audit(capture,{now});
const good=R.register({id:'research-001'},[capture],[audit]);
assert.equal(good.accepted_integrity_count,1);
assert.equal(good.evidence[0].integrity_status,'CONSISTENT_UNVERIFIED');
assert.equal(good.eligible_for_real_world_scoring,false);
assert.ok(good.evidence[0].reasons.includes('OUTCOME_NOT_VERIFIED'));
assert.throws(()=>R.register({id:'x'},[capture],[]),/Every capture/);
assert.throws(()=>R.register({id:'x'},[capture,capture],[audit,audit]),/Duplicate/);
const changed={bytes:Buffer.from(bytes),receipt:{...capture.receipt}};changed.bytes[0]^=1;
assert.throws(()=>R.register({id:'x'},[changed],[A.audit(changed,{now})]),/Audit hash does not match capture/);
const staleAudit=A.audit(capture,{now:now+86400001});
const rejected=R.register({id:'x'},[capture],[staleAudit]);
assert.equal(rejected.rejected_count,1);
assert.equal(rejected.evidence[0].integrity_status,'REJECTED');
assert.throws(()=>R.register({id:'x'},[capture],[{...audit,computed_sha256:'a'.repeat(64)}]),/Audit hash/);
console.log('PASS Cardano evidence register provenance and negative cases');
