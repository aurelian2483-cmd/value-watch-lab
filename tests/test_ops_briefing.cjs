'use strict';
const assert=require('node:assert/strict');
const B=require('../ops-control/briefing.js');
const makeFeed=(id,ok=true,stale=false)=>({id,ok,stale,gateOK:true,age:1000});
const clean=[makeFeed('football'),makeFeed('racing'),makeFeed('sports'),makeFeed('horse')];
const incident={key:'issue-one',state:'ACTIVE',owner:'Horse Racing Manager',priority:'P2',firstSeen:'2026-11-11T10:00:00Z',lastSeen:'2026-11-12T10:00:00Z',occurrences:3,reopenCount:1};
const t0='2026-11-12T10:00:00Z',t1='2026-11-12T11:00:00Z',t2='2026-11-13T10:00:00Z';
const s0=B.snapshot(t0,clean,{incidents:[incident]},true);
const zero=B.make(B.blank(),s0,{incidents:[incident]});
assert.equal(zero.comparison,'NO_PREVIOUS_AUDIT');
assert.equal(zero.agedCount,1);assert.equal(zero.repeatedCount,1);assert.equal(zero.reopenedCount,1);
assert.equal(zero.openP2,1);assert.equal(zero.clearedCount,0);
const s1=B.snapshot(t1,clean.map(f=>f.id==='football'?{...f,stale:true}:f),{incidents:[incident]},false);
const delta=B.make(B.advance(B.blank(),s0),s1,{incidents:[incident]});
assert.equal(delta.comparison,'PREVIOUS_AUDIT_SAME_UK_DAY');
assert.deepEqual(delta.degradedFeeds,['football']);
assert.equal(delta.clearedCount,0);assert.equal(delta.complete,false);
assert.match(delta.priority,/DETERIORATION/);
const p1={...incident,key:'urgent',priority:'P1',firstSeen:t1,occurrences:1,reopenCount:0};
const bad=B.snapshot(t1,[...clean],{incidents:[incident,p1]},true);
const alert=B.make(B.advance(B.blank(),s0),bad,{incidents:[incident,p1]});
assert.equal(alert.openP1,1);assert.equal(alert.newCount,1);assert.equal(alert.priority,'URGENT REVIEW');
const state=B.advance(B.advance(B.blank(),s0),s1);
assert.equal(state.days.length,1,'same UK day replaces daily last');
assert.equal(state.days[0].first.at,t0);assert.equal(state.days[0].last.at,t1);
const s2=B.snapshot(t2,clean,{incidents:[]},true);
const cleared=B.make(state,s2,{incidents:[]});
assert.equal(cleared.comparison,'PREVIOUS_AUDIT_PRIOR_UK_DAY');
assert.equal(cleared.clearedCount,1);
const unavailable=B.make(state,B.snapshot(t2,clean,{incidents:[]},false),{incidents:[]});
assert.equal(unavailable.clearedCount,0,'incomplete audits cannot claim clearance');
const mem=new Map();const store={getItem:k=>mem.has(k)?mem.get(k):null,setItem:(k,v)=>mem.set(k,v)};
assert.equal(B.load(store).available,true);
assert.equal(B.save(store,state),true);
assert.equal(B.load(store).state.days.length,1);
mem.set(B.KEY,'invalid');
assert.equal(B.load(store).available,false,'corruption must be visible');
assert.equal(mem.get(B.KEY),'invalid','corrupt data must not be silently rewritten');
const blocked={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}};
assert.equal(B.save(blocked,state),false);
assert.equal(B.load(blocked).available,false);
let days=B.blank();for(let i=0;i<60;i++){const iso=new Date(Date.UTC(2026,0,i+1,12)).toISOString();days=B.advance(days,B.snapshot(iso,clean,{incidents:[]},true));}
assert.equal(days.days.length,B.MAX_DAYS,'bounded UK-day retention');
assert.equal(days.last.date,days.days.at(-1).date);
console.log('PASS: daily Director audit deltas, P1 escalation, degradation, age, reopens, safe closures, UK days and bounded local history');
