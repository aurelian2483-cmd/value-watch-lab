'use strict';
const assert=require('node:assert/strict');
const {historySignals}=require('../scripts/horse_v3_history_reliability.cjs');
const h=(id,date,pos,going='Standard',distance_yards=1760)=>({race_id:id,date,run_type:'FLAT',position:pos,runner_count:8,going,distance_yards});
