'use strict';
const assert=require('node:assert/strict');
const D=require('../darts/model.js');
assert.equal(D.VERSION,'DARTS_ELO_K24_RESEARCH_V1');
assert.equal(D.prob(1500,1500),.5);
assert.ok(D.prob(1600,1500)>.5);
const first='2026-09-01T10:00:00Z';
const player_a={id:'pA',name:'A'},player_b={id:'pB',name:'B'};
const results=Array.from({length:8},(_,i)=>({id:'m'+i,played_at:'2026-09-'+String(i+1).padStart(2,'0')+'T10:00:00Z',status:'FINAL',player_a,player_b,winner_id:'pA'}));
const fixture={id:'up1',start_utc:'2099-01-01T20:00:00Z',status:'SCHEDULED',competition:'Research only',player_a,player_b};
const report=D.model(results,[fixture],'2026-11-15T20:00:00Z');
assert.equal(report.training_matches,8);
assert.equal(report.fixtures.length,1);
assert.ok(report.fixtures[0].prob_a>.5);
assert.ok(Math.abs(report.fixtures[0].prob_a+report.fixtures[0].prob_b-1)<1e-12);
assert.equal(report.betting_eligible,false);
assert.equal(report.publication_gate,'BLOCKED');
assert.equal(D.model(results,[fixture],'2026-11-15T20:00:00Z').fixtures[0].prob_a,report.fixtures[0].prob_a);
assert.equal(D.model(results.slice(0,7),[fixture],'2026-11-15T20:00:00Z').fixtures[0].prob_a,null);
assert.throws(()=>D.model([...results,results[0]],[fixture],'2026-11-15T20:00:00Z'),/duplicated/);
assert.throws(()=>D.model(results.map((r,i)=>i===0?{...r,played_at:'2026-12-01T20:00:00Z'}:r),[fixture],'2026-11-15T20:00:00Z'),/after model snapshot/);
assert.throws(()=>D.model(results,[{...fixture,start_utc:'2026-11-15T20:01:00Z'}],'2026-11-15T20:00:00Z'),/non-upcoming/);
assert.throws(()=>D.model(results,[{...fixture,player_b:player_a}],'2026-11-15T20:00:00Z'),/non-upcoming/);
assert.throws(()=>D.model(results,[fixture,fixture],'2026-11-15T20:00:00Z'),/duplicated/);
assert.deepEqual(D.model([],[],'2026-11-15T20:00:00Z').fixtures,[]);
console.log('Darts research model: 14 deterministic and fail-closed assertions passed');
