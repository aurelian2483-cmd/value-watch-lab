'use strict';
const assert=require('node:assert/strict');
const {audit,isoDate,key}=require('../research/market-benchmark/epl-608-coverage.cjs');
const header='Date,HomeTeam,AwayTeam,FTR,AvgCH,AvgCD,AvgCA';
const row='16/08/2025,Arsenal,Chelsea,H,2.1,3.3,4.2';
const fixtures=[{date:'2025-08-16',home:'Arsenal',away:'Chelsea',result:'H'}];
assert.equal(isoDate('16/08/2025'),'2025-08-16');
assert.equal(isoDate('2025-02-30'),null);
assert.equal(key('2025-08-16',' ARSENAL ','Chelsea'),key('16/08/2025','arsenal','chelsea'));
const good=audit(fixtures,header+'\n'+row+'\n');
assert.equal(good.counts.matched_complete_odds,1);
assert.equal(good.counts.eligible_prospective_model_market_pairs,0);
assert.equal(good.publication_gate,'BLOCKED');
assert.equal(audit(fixtures,header+'\n'+row+'\n'+row+'\n').counts.ambiguous_odds_identity,1);
assert.equal(audit(fixtures,header+'\n16/08/2025,Arsenal,Chelsea,A,2.1,3.3,4.2\n').counts.outcome_disagreement,1);
assert.equal(audit(fixtures,header+'\n16/08/2025,Arsenal,Chelsea,H,2.1,,4.2\n').counts.missing_or_invalid_complete_odds,1);
assert.equal(audit(fixtures,header+'\n').counts.unmatched_fixture,1);
assert.equal(audit([...fixtures,...fixtures],header+'\n'+row+'\n').counts.duplicate_replay_fixtures,1);
assert.throws(()=>audit(fixtures,'Date,HomeTeam,HomeTeam,AwayTeam,FTR,AvgCH,AvgCD,AvgCA\n'+row+'\n'));
console.log('EPL 608 coverage audit: synthetic safeguards passed');
