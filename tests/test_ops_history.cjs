'use strict';
const assert=require('node:assert/strict');
const H=require('../ops-control/history.js');
const mem=new Map();
const storage={getItem:k=>mem.has(k)?mem.get(k):null,setItem:(k,v)=>mem.set(k,v)};
const t0='2026-11-12T12:00:00.000Z',t1='2026-11-12T13:00:00.000Z',t2='2026-11-12T14:00:00.000Z',t3='2026-11-12T15:00:00.000Z';
const warning={owner:'Horse Racing Manager',priority:'P2',recommendedAction:'Reconcile meeting discovery and exclusions with published racecards.',observations:['Racing: full external meeting coverage is not verified']};
const empty=[{owner:'Operations Director',priority:'P3',recommendedAction:'Continue routine monitoring.',observations:['No source, age or gate exception in this browser audit']}];
const base=H.load(storage);assert.equal(base.available,true);assert.deepEqual(base.state.incidents,[]);
const first=H.reconcile(base.state,[warning],t0,true);
assert.equal(first.incidents.length,1);assert.equal(first.incidents[0].state,'ACTIVE');assert.equal(first.incidents[0].occurrences,1);assert.equal(first.incidents[0].firstSeen,t0);
assert.equal(H.save(storage,first),true);assert.equal(H.load(storage).state.incidents[0].firstSeen,t0);
const recurring=H.reconcile(first,[warning],t1,true);
assert.equal(recurring.incidents[0].occurrences,2);assert.equal(recurring.incidents[0].reopenCount,0);assert.equal(recurring.incidents[0].lastSeen,t1);
const incomplete=H.reconcile(recurring,empty,t2,false);
assert.equal(incomplete.incidents[0].state,'ACTIVE','Incomplete audit must not close an incident');
const resolved=H.reconcile(incomplete,empty,t2,true);
assert.equal(resolved.incidents[0].state,'RESOLVED');assert.equal(resolved.incidents[0].resolvedAt,t2);
const reopened=H.reconcile(resolved,[warning],t3,true);
assert.equal(reopened.incidents[0].state,'ACTIVE');assert.equal(reopened.incidents[0].reopenCount,1);assert.equal(reopened.incidents[0].firstSeen,t0);
assert.equal(reopened.incidents[0].resolvedAt,null);
assert.equal(H.identity(warning),H.identity({...warning,observations:['Different evidence'],priority:'P1'}));
const failedStorage={getItem(){throw Error('Storage disabled')},setItem(){throw Error('Storage disabled')}};
assert.equal(H.load(failedStorage).available,false);assert.equal(H.save(failedStorage,reopened),false);
mem.set(H.KEY,'{"schemaVersion":999}');const corrupt=H.load(storage);
assert.equal(corrupt.available,false);assert.equal(corrupt.state.incidents.length,0);assert.equal(mem.get(H.KEY),'{"schemaVersion":999}','Corrupt storage must not be overwritten silently');
const many=[];for(let i=0;i<260;i++)many.push({owner:'Unique owner '+i,recommendedAction:'Follow up '+i,priority:'P2',observations:['Observed']});
const bounded=H.reconcile(H.load({getItem:()=>null}).state,many,t0,true);
assert.equal(bounded.incidents.length,H.MAX_ITEMS);
assert(bounded.incidents.every(e=>e.state==='ACTIVE'));
console.log('PASS: browser-local history, repeat detection, fail-closed resolution, re-open, bounded retention, storage-failure safety');
