'use strict';
const assert = require('node:assert/strict');
const S = require('../paper-lab/store.js');
const tasks = [];
const store = S.createStore({ odds: 2, filter: 'all' }, fn => tasks.push(fn));
let oddsUpdates = 0, filterUpdates = 0;
store.subscribe(s => s.odds, () => oddsUpdates++);
const unsubscribe = store.subscribe(s => s.filter, () => filterUpdates++);
store.update(s => ({ ...s, odds: 2.1 }));
store.update(s => ({ ...s, odds: 2.2 }));
assert.equal(tasks.length, 1);
tasks.shift()();
assert.equal(oddsUpdates, 1);
assert.equal(filterUpdates, 0);
unsubscribe();
store.update(s => ({ ...s, filter: 'tennis' })); tasks.shift()();
assert.equal(filterUpdates, 0);
const records = new Map(), errors = [];
const storage = { getItem: k => records.get(k) ?? null, setItem: (k,v) => records.set(k,v) };
const persistence = S.createPersistence(storage, 'test', value => { assert.equal(value.version, 1); return value; }, message => errors.push(message));
assert.equal(persistence.read(), null);
assert.equal(persistence.write({version:1}), true);
records.set('test', '{"version":1,"otherTab":true}');
assert.equal(persistence.write({version:1,local:true}), false);
assert.equal(persistence.locked, true);
assert(records.get('test').includes('otherTab'));
assert(errors[0].includes('another tab'));
records.set('broken', 'not JSON');
const broken = S.createPersistence(storage, 'broken', x=>x, message=>errors.push(message));
assert.equal(broken.read(), null);
assert.equal(broken.write({}), false);
assert.equal(records.get('broken'), 'not JSON');
(async () => {
  const snapshot = { slot: { legs: [{name:'Original'}] }, publication_gate:'BLOCKED' };
  const record = await S.seal(snapshot, require('node:crypto').webcrypto);
  snapshot.slot.legs[0].name = 'Changed';
  assert.equal(await S.verify(record, require('node:crypto').webcrypto), true);
  record.snapshot.slot.legs[0].name = 'Tampered';
  assert.equal(await S.verify(record, require('node:crypto').webcrypto), false);
  assert.equal(record.independentlyAttested, false);
  console.log('Research store: localized subscriptions, batched updates, storage conflict recovery and snapshot integrity passed');
})().catch(e => { console.error(e); process.exitCode = 1; });
